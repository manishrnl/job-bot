#!/usr/bin/env python3
"""jobbot: LinkedIn-profile -> tailored ATS resume -> auto apply. Run `./jb` for the menu or `./jb -h`."""
import argparse
import json
import sys
from pathlib import Path

from rich.prompt import Prompt
from rich.table import Table

from jobbot import ai, ats, render, tracker
from jobbot import profile as prof
from jobbot.config import CFG, OUT, PROFILE_PATH
from jobbot.pipeline import console, report_table, tailored_resume

LOGIN_URLS = {
    "linkedin": "https://www.linkedin.com/login",
    "hirist": "https://www.hirist.tech/login",
    "naukri": "https://www.naukri.com/nlogin/login",
}


def cmd_init(a):
    paths = [Path(p).expanduser() for p in a.pdf]
    for p in paths:
        if not p.exists():
            raise SystemExit(f"File not found: {p}")
    console.print(f"Using AI backend: [bold]{ai.backend()}[/]")
    with console.status("Reading your profile..."):
        p = prof.build(paths)
    console.print(f"[green]Saved {PROFILE_PATH}[/]: {p.get('name')} | {len(p.get('experience', []))} roles, "
                  f"{len(p.get('skills', []))} skills, {len(p.get('projects', []))} projects")
    if not (p.get("contact") or {}).get("phone"):
        console.print("[yellow]No phone number found. Add it under contact: in config.yaml.[/]")
    if sys.stdin.isatty():
        cmd_complete(a)
    else:
        console.print("Next: [bold]./jb complete[/] to fill in what the PDF didn't have.")


def _months(s):
    import datetime
    if not s or s.lower().startswith("present"):
        d = datetime.date.today()
        return d.year * 12 + d.month
    try:
        d = datetime.datetime.strptime(s[:8].strip(), "%b %Y")
        return d.year * 12 + d.month
    except ValueError:
        return None


def total_years(p):
    months = 0
    for x in p.get("experience") or []:
        if "intern" in (x.get("title") or "").lower():
            continue
        s, e = _months(x.get("start")), _months(x.get("end") or "Present")
        if s and e and e >= s:
            months += e - s + 1
    return months // 12


def _save_config(cfg):
    import yaml
    root = Path(__file__).resolve().parent
    (root / "config.yaml").write_text(
        "# Generated by ./jb complete. See config.example.yaml for what each setting does.\n"
        + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))


def _set_answer(cfg, first_match, value):
    for r in cfg["answers"]:
        if r["match"][0] == first_match:
            r["answer"] = str(value)
            return


def cmd_complete(a):
    """Ask for everything the LinkedIn PDF doesn't contain; save to profile.json + config.yaml."""
    p = prof.load()
    cfg = CFG
    c = p.setdefault("contact", {})
    ask = lambda q, d="": Prompt.ask(q, default=d or None) or ""
    console.print("\n[bold]Filling in what the PDF didn't have[/] (Enter keeps the value in brackets)\n")

    c["phone"] = ask("Phone", c.get("phone", ""))
    c["location"] = ask("Current city", c.get("location", ""))
    links = list(c.get("links") or [])
    if not any("github" in l for l in links):
        gh = ask("GitHub URL (blank to skip)")
        if gh:
            links.append(gh)
    if not any("github" not in l and "linkedin" not in l for l in links):
        site = ask("Portfolio/website URL (blank to skip)")
        if site:
            links.append(site)
    c["links"] = links

    for ed in p.get("education") or []:
        if not ed.get("end"):
            ed["start"] = ask(f"{ed.get('degree')}: start year", ed.get("start", ""))
            ed["end"] = ask(f"{ed.get('degree')}: end year", ed.get("end", ""))
            cg = ask("CGPA/percentage (blank to skip)")
            if cg:
                ed["details"] = f"CGPA: {cg}" if "." in cg and float(cg.rstrip('%')) <= 10 else f"Score: {cg}"

    if not p.get("projects") and Prompt.ask("Add projects? (resumes with 1-3 projects do better)",
                                            choices=["y", "n"], default="y") == "y":
        while True:
            name = ask("Project name (blank to finish)")
            if not name:
                break
            p.setdefault("projects", []).append({
                "name": name,
                "tech": [t.strip() for t in ask("Tech used (comma separated)").split(",") if t.strip()],
                "link": ask("Link (blank to skip)"),
                "details": [d.strip() for d in ask("What it does + any numbers (separate points with ;)").split(";") if d.strip()],
            })
    PROFILE_PATH.write_text(json.dumps(p, indent=2, ensure_ascii=False))

    cfg["contact"].update(phone=c["phone"], location=c["location"], links=c["links"])
    _set_answer(cfg, "total experience", ask("Total years of experience", str(total_years(p))))
    _set_answer(cfg, "notice period", ask("Notice period in days", "30"))
    _set_answer(cfg, "current ctc", ask("Current CTC in rupees per year (e.g. 800000)"))
    _set_answer(cfg, "expected ctc", ask("Expected CTC in rupees per year"))
    cfg["search"]["keywords"] = [k.strip() for k in ask(
        "Job titles to search (comma separated)", ", ".join(cfg["search"]["keywords"])).split(",") if k.strip()]
    cfg["search"]["location"] = ask("Job location to search", cfg["search"]["location"])
    cfg["resume"]["target_role"] = ask("Main target role for the master resume",
                                       cfg["resume"].get("target_role") or cfg["search"]["keywords"][0])
    _save_config(cfg)
    console.print("\n[green]Saved profile.json and config.yaml.[/] Next: [bold]./jb build[/]")


def cmd_build(a):
    p = prof.load()
    from jobbot.tailor import build_base
    with console.status("Writing your master resume..."):
        resume, rep = build_base(p, a.role)
        pdf = render.save(resume, render.slug("master", a.role or CFG["resume"].get("target_role", "")))
        pdf.with_suffix(".json").write_text(json.dumps({"resume": resume, "report": rep}, indent=2, ensure_ascii=False))
    report_table(rep, pdf)


def _read_jd(a):
    if a.jd:
        return Path(a.jd).expanduser().read_text()
    console.print("Paste the job description, then press Ctrl-D:")
    return sys.stdin.read()


def cmd_tailor(a):
    p = prof.load()
    if a.url:
        from jobbot.browser import session
        with session() as (pw, ctx, page):
            page.goto(a.url, wait_until="domcontentloaded")
            page.wait_for_timeout(3000)
            jd = page.inner_text("body")
            tailored_resume(p, jd, a.title or page.title(), a.company, pw=pw)
    else:
        tailored_resume(p, _read_jd(a), a.title, a.company)


def cmd_score(a):
    path = Path(a.resume).expanduser()
    text = prof.pdf_text(path) if path.suffix.lower() == ".pdf" else path.read_text()
    jd = _read_jd(a)
    with console.status("Extracting JD keywords..."):
        kw = ai.ask_json("List the keywords an ATS would match for this job description. JSON: "
                         '{"must": [max 15 required hard skills/tools, JD spelling], "nice": [max 15 nice-to-have]}\n\n'
                         + jd[:12000])
    rep = ats.score(text, kw.get("must", []), kw.get("nice", []))
    report_table(rep)


def cmd_login(a):
    from jobbot.browser import session
    url = LOGIN_URLS.get(a.site, a.site)
    with session(headless=False) as (pw, ctx, page):
        try:
            page.goto(url, wait_until="domcontentloaded", timeout=60000)
        except Exception as e:
            raise SystemExit(
                f"Could not reach {url}. Check your internet/DNS and try again. "
                "If LinkedIn is blocked on this network, use a different connection or log in through a browser with working internet access."
            ) from e
        input(f"Log in to {a.site} in the browser window (solve any captcha/OTP), then press Enter here... ")
    console.print("[green]Session saved.[/] You won't need to log in again until it expires.")


def cmd_use_chrome(a):
    import subprocess
    from jobbot.browser import chrome_profiles, import_chrome
    profs = chrome_profiles()
    if not profs:
        raise SystemExit(
            "No Chrome profiles were found. Install or launch Chrome once, sign in, and retry. "
            "If you use a different Chrome profile or browser, use './jb login linkedin' instead."
        )
    t = Table("#", "Chrome profile", "Account")
    for i, (d, name, email) in enumerate(profs, 1):
        t.add_row(str(i), name, email or "-")
    if a.profile:
        want = a.profile.strip().lower()
        i = next((n for n, (d, name, email) in enumerate(profs, 1)
                  if want in (d.lower(), name.lower(), (email or "").lower())), None)
        if i is None:
            console.print(t)
            raise SystemExit(f"No Chrome profile matching '{a.profile}'. Use a name from the table above.")
    else:
        console.print(t)
        i = int(Prompt.ask("Which profile is logged in to LinkedIn/Hirist?",
                           choices=[str(n) for n in range(1, len(profs) + 1)]))
    if sys.platform == "win32":
        running = "chrome.exe" in subprocess.run(["tasklist", "/FI", "IMAGENAME eq chrome.exe"],
                                                 capture_output=True, text=True).stdout.lower()
    else:
        name = "Google Chrome" if sys.platform == "darwin" else "chrome"
        running = subprocess.run(["pgrep", "-x", name], capture_output=True).returncode == 0
    if running:
        console.print("[yellow]Chrome is open. Quit it (Cmd+Q) so your latest logins are saved to disk.[/]")
        input("Press Enter after quitting Chrome... ")
    with console.status("Copying profile..."):
        import_chrome(profs[i - 1][0])
    console.print(f"[green]Done. The bot now uses a copy of '{profs[i - 1][1]}' with your logins.[/] "
                  "You can reopen Chrome; both run side by side.")


def cmd_apply(a):
    p = prof.load()
    from jobbot.browser import session
    s = CFG["search"]
    keywords = a.keywords or s.get("keywords") or []
    location = a.location or s.get("location", "")
    limit = a.limit or CFG["apply"].get("max_per_run", 10)
    if a.posted:
        from jobbot.platforms.linkedin_public import posted_seconds
        if not posted_seconds(a.posted):
            raise SystemExit("--posted takes values like 30m, 1h, 6h, 24h, 3d, 1w")
        CFG["search"]["posted_within"] = a.posted
    root = Path(__file__).resolve().parent
    if not a.dry_run and (root / "config.yaml").read_text() == (root / "config.example.yaml").read_text():
        raise SystemExit("config.yaml still has the placeholder answers (CTC, notice period...). Run ./jb complete first.")
    blank = [r["match"][0] for r in CFG.get("answers") or [] if str(r.get("answer", "")).strip() == ""]
    if blank and not a.dry_run:
        raise SystemExit(f"Fill these in config.yaml > answers before a live run: {', '.join(blank)}")
    console.print(f"AI: [bold]{ai.backend()}[/] | limit {limit} | {'[cyan]DRY RUN[/]' if a.dry_run else '[bold red]LIVE[/]'}")
    with session() as (pw, ctx, page):
        if a.platform == "url":
            from jobbot.platforms import generic
            for u in a.urls:
                console.print(f"=> {generic.apply(pw, page, p, u)}")
            return
        if not keywords:
            raise SystemExit("No keywords. Pass --keywords or set search.keywords in config.yaml")
        if a.platform == "linkedin":
            from jobbot.platforms import linkedin as plat
        else:
            from jobbot.platforms import hirist as plat
        n = plat.apply(pw, page, p, keywords, location, limit, dry_run=a.dry_run)
    tracker.write_run_summary(a.platform, submitted=n, dry_run=a.dry_run, limit=limit)
    console.print(f"\n[bold green]Done: {n} application(s) {'simulated' if a.dry_run else 'submitted'}.[/]")


def cmd_history(a):
    t = Table("When", "Site", "Status", "ATS", "Fit", "Title", "Company", "Link")
    for at, plat, status, score, fit, title, company, url in tracker.rows(a.n, a.status):
        t.add_row(at.replace("T", " ")[:16], plat, status, str(score or ""), str(fit or ""),
                  (title or "")[:40], (company or "")[:22], url or "")
    console.print(t)


def cmd_clean(a):
    import shutil
    from jobbot.config import BROWSER_DIR, DATA
    targets = [(OUT, "generated resumes (output/)", True),
               (DATA / "debug", "debug screenshots", True),
               (DATA / "answers_cache.json", "cached form answers", True),
               (DATA / "jobs.db", "application history + stats", a.all or a.history),
               (DATA / "applications.csv", "history CSV", a.all or a.history),
               (PROFILE_PATH, "imported profile", a.all),
               (BROWSER_DIR, "saved browser login", a.all or a.logout)]
    chosen = [(p, label) for p, label, on in targets if on and p.exists()]
    if not chosen:
        return console.print("Nothing to clean.")
    for p, label in chosen:
        console.print(f"  - {label}: {p}")
    if not a.yes and Prompt.ask("Delete these?", choices=["y", "n"], default="n") != "y":
        return console.print("Cancelled.")
    for p, _ in chosen:
        if p.is_dir():
            shutil.rmtree(p)
        else:
            p.unlink()
    OUT.mkdir(exist_ok=True)
    console.print("[green]Cleaned.[/]")


def cmd_stats(a):
    s = tracker.stats()
    console.print(f"\n[bold green]Applied total: {s['total_applied']}[/]   today: [bold]{s['applied_today']}[/]   "
                  f"avg ATS score of applied: [bold]{s['avg_score'] or '-'}[/]")
    if s["by_platform"]:
        console.print("By site: " + ", ".join(f"{k} {v}" for k, v in s["by_platform"].items()))
    t = Table("Status", "Jobs", title="All jobs seen")
    for k, v in sorted(s["by_status"].items(), key=lambda x: -x[1]):
        t.add_row(k, str(v))
    console.print(t)
    if s["per_day"]:
        d = Table("Day", "Applied", title="Last 14 days")
        for day, n in s["per_day"]:
            d.add_row(day, "█" * min(n, 40) + f" {n}")
        console.print(d)
    console.print(f"[dim]Full log with links, scores and resume paths: {tracker.DATA / 'applications.csv'}[/]")


def menu():
    console.print("[bold]jobbot[/]  your resume + auto-apply assistant\n")
    has_profile = PROFILE_PATH.exists()
    opts = [
        ("1", "Import LinkedIn profile PDF", "init"),
        ("2", "Build master resume (no JD)", "build"),
        ("3", "Tailor resume for a job description", "tailor"),
        ("4", "Score an existing resume against a JD", "score"),
        ("5", "Use my Chrome logins / log in to a site", "login"),
        ("6", "Auto-apply on LinkedIn (Easy Apply)", "linkedin"),
        ("7", "Auto-apply on Hirist (beta)", "hirist"),
        ("8", "Pre-fill an application on any URL", "url"),
        ("9", "Application history + stats", "history"),
        ("10", "Clean old resumes / data", "clean"),
    ]
    for k, label, _ in opts:
        console.print(f"  [bold cyan]{k}[/]  {label}")
    if not has_profile:
        console.print("\n[yellow]Start with 1.[/]")
    choice = Prompt.ask("\nChoose", choices=[o[0] for o in opts])
    action = dict((o[0], o[2]) for o in opts)[choice]
    argv = {
        "init": lambda: ["init", Prompt.ask("Path to LinkedIn profile PDF").strip().strip("'\"")],
        "build": lambda: ["build"] + (["--role", r] if (r := Prompt.ask("Target role", default="")) else []),
        "tailor": lambda: ["tailor"] + (["--url", u] if (u := Prompt.ask("Job URL (blank to paste JD)", default="")) else []),
        "score": lambda: ["score", Prompt.ask("Resume path (.pdf/.txt)").strip().strip("'\"")],
        "login": lambda: (["use-chrome"] if Prompt.ask("Copy logins from your Chrome?", choices=["y", "n"], default="y") == "y"
                          else ["login", Prompt.ask("Site", choices=["linkedin", "hirist", "naukri"], default="linkedin")]),
        "linkedin": lambda: ["apply", "linkedin"] + (["--dry-run"] if Prompt.ask("Dry run first?", choices=["y", "n"], default="y") == "y" else []),
        "hirist": lambda: ["apply", "hirist"] + (["--dry-run"] if Prompt.ask("Dry run first?", choices=["y", "n"], default="y") == "y" else []),
        "url": lambda: ["apply", "url", Prompt.ask("Job/application URL")],
        "history": lambda: ["stats"],
        "clean": lambda: ["clean"] + (["--history"] if Prompt.ask("Also delete application history?",
                                                                   choices=["y", "n"], default="n") == "y" else []),
    }[action]()
    main(argv)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="jb", description="LinkedIn profile -> tailored ATS resume -> auto apply")
    sub = ap.add_subparsers(dest="cmd")

    s = sub.add_parser("init", help="import LinkedIn profile PDF (+ optional old resume PDFs)")
    s.add_argument("pdf", nargs="+")
    s.set_defaults(fn=cmd_init)

    s = sub.add_parser("complete", help="fill in details missing from the LinkedIn PDF (CTC, projects...)")
    s.set_defaults(fn=cmd_complete)

    s = sub.add_parser("build", help="build a polished master resume (no JD)")
    s.add_argument("--role", default="")
    s.set_defaults(fn=cmd_build)

    s = sub.add_parser("tailor", help="tailor resume to one job (JD file, stdin, or URL)")
    s.add_argument("--jd", help="text file with the job description")
    s.add_argument("--url", help="job posting URL (read in the browser)")
    s.add_argument("--title", default="")
    s.add_argument("--company", default="")
    s.set_defaults(fn=cmd_tailor)

    s = sub.add_parser("score", help="ATS-score any resume (pdf/txt) against a JD")
    s.add_argument("resume")
    s.add_argument("--jd", help="text file with the job description (else paste)")
    s.set_defaults(fn=cmd_score)

    s = sub.add_parser("use-chrome", help="copy your real Chrome profile (with logins) into the bot")
    s.add_argument("--profile", help='Chrome profile folder, e.g. "Default" (your main profile)')
    s.set_defaults(fn=cmd_use_chrome)

    s = sub.add_parser("login", help="log in once to linkedin / hirist / naukri / <url>")
    s.add_argument("site")
    s.set_defaults(fn=cmd_login)

    s = sub.add_parser("apply", help="auto apply: linkedin | hirist | url <URL...>")
    s.add_argument("platform", choices=["linkedin", "hirist", "url"])
    s.add_argument("urls", nargs="*", help="for `apply url`")
    s.add_argument("-k", "--keywords", nargs="+", help='e.g. -k "Python Developer" "Backend Engineer"')
    s.add_argument("-l", "--location")
    s.add_argument("-n", "--limit", type=int)
    s.add_argument("-t", "--posted", help="only jobs posted within: 30m, 1h, 6h, 24h, 3d, 1w (default: config)")
    s.add_argument("--dry-run", action="store_true", help="do everything except clicking Submit")
    s.set_defaults(fn=cmd_apply)

    s = sub.add_parser("history", help="show applications log (with links)")
    s.add_argument("-n", type=int, default=50)
    s.add_argument("--status", help="e.g. applied, low_fit, error")
    s.set_defaults(fn=cmd_history)

    s = sub.add_parser("stats", help="how many applied, today, avg score, by status")
    s.set_defaults(fn=cmd_stats)

    s = sub.add_parser("clean", help="delete generated resumes, debug files, answer cache (history kept)")
    s.add_argument("--history", action="store_true", help="also delete application history/stats")
    s.add_argument("--logout", action="store_true", help="also delete the saved browser login")
    s.add_argument("--all", action="store_true", help="everything above + imported profile (fresh start)")
    s.add_argument("-y", "--yes", action="store_true", help="don't ask for confirmation")
    s.set_defaults(fn=cmd_clean)

    a = ap.parse_args(argv)
    if not a.cmd:
        return menu()
    try:
        a.fn(a)
    except KeyboardInterrupt:
        console.print("\n[yellow]Stopped.[/]")


if __name__ == "__main__":
    main()
